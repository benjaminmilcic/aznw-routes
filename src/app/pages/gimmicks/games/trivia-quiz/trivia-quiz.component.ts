import { CommonModule } from '@angular/common';
import {
  ChangeDetectionStrategy,
  Component,
  DestroyRef,
  OnInit,
  computed,
  inject,
  signal,
} from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import { TranslateModule, TranslateService } from '@ngx-translate/core';
import { GamesService } from '../games.service';
import {
  AnswerLetter,
  QuestionLanguage,
  TriviaQuestion,
} from './trivia-quiz.model';
import { TriviaQuizService } from './trivia-quiz.service';

/** Number of questions per round. */
const QUESTIONS_PER_ROUND = 15;

/**
 * Playback speed of the explanation. The audio files are deliberately
 * spoken calmly; here the tempo can be adjusted without having to
 * regenerate them. The pitch is preserved, the browser takes care
 * of that by itself.
 */
const PLAYBACK_RATE = 1.0;

/**
 * Quiz "Did you know?" with three answer options and an explanation.
 * The questions come from the database (table trivia_questions) via the API,
 * the illustrations are in the frontend under assets/quiz-illustrations/.
 */
@Component({
  selector: 'app-trivia-quiz',
  imports: [CommonModule, TranslateModule],
  templateUrl: './trivia-quiz.component.html',
  styleUrl: './trivia-quiz.component.css',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class TriviaQuizComponent implements OnInit {
  private readonly quizService = inject(TriviaQuizService);
  private readonly gamesService = inject(GamesService);
  private readonly translate = inject(TranslateService);
  private readonly destroyRef = inject(DestroyRef);

  protected readonly loading = signal(true);
  protected readonly loadFailed = signal(false);
  protected readonly questions = signal<TriviaQuestion[]>([]);
  protected readonly index = signal(0);
  /** Clicked answer of the current question, null as long as not answered. */
  protected readonly selected = signal<AnswerLetter | null>(null);
  protected readonly rightAnswers = signal(0);
  protected readonly wrongAnswers = signal(0);
  protected readonly finished = signal(false);

  protected readonly total = computed(() => this.questions().length);
  protected readonly current = computed<TriviaQuestion | null>(
    () => this.questions()[this.index()] ?? null
  );
  protected readonly answered = computed(() => this.selected() !== null);
  protected readonly isRight = computed(
    () => this.selected() === this.current()?.correctAnswer
  );
  protected readonly explanationParagraphs = computed(() =>
    (this.current()?.explanation ?? '').split('\n\n').filter((part) => !!part)
  );
  /**
   * Read-aloud explanation. The files are ready in the frontend and are
   * generated by nest-aznw-api/db/trivia-quellen/build_trivia_audio.py, named
   * after language and question number. That's why the path is enough here, it needs
   * neither an API call nor a field in the database.
   */
  protected readonly audioUrl = computed(() => {
    const question = this.current();
    return question
      ? `/assets/trivia-audio/${question.language}/${question.questionNumber}.mp3`
      : null;
  });
  protected readonly speaking = signal(false);
  /** Newly written questions do not have an audio file yet. */
  protected readonly audioMissing = signal(false);
  private audio: HTMLAudioElement | null = null;
  protected readonly answeredCount = computed(
    () => this.rightAnswers() + this.wrongAnswers()
  );
  /** Share of correct answers in percent, 0 if nothing has been answered yet. */
  protected readonly percentRight = computed(() => {
    const answered = this.answeredCount();
    return answered === 0
      ? 0
      : Math.round((this.rightAnswers() * 100) / answered);
  });

  ngOnInit(): void {
    this.gamesService.changeGameName.next('trivia-quiz');
    this.loadQuestions();
    this.translate.onLangChange
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe(() => this.translateRound());
    // Otherwise the explanation keeps talking after the page was left.
    this.destroyRef.onDestroy(() => this.stopSpeech());
  }

  /**
   * Starts or pauses the explanation. If the audio file is missing, the button
   * disappears; that only happens for questions that have no audio generated yet.
   */
  protected toggleSpeech(): void {
    if (this.speaking()) {
      this.stopSpeech();
      return;
    }
    const url = this.audioUrl();
    if (!url) {
      return;
    }
    const audio = (this.audio ??= new Audio());
    if (audio.getAttribute('src') !== url) {
      audio.setAttribute('src', url);
      audio.load();
    }
    // After a source change the speed falls back to 1.
    audio.playbackRate = PLAYBACK_RATE;
    audio.onended = () => this.speaking.set(false);
    audio.onerror = () => {
      this.speaking.set(false);
      this.audioMissing.set(true);
    };
    audio
      .play()
      .then(() => this.speaking.set(true))
      .catch(() => {
        this.speaking.set(false);
        this.audioMissing.set(true);
      });
  }

  private stopSpeech(): void {
    this.speaking.set(false);
    if (this.audio) {
      this.audio.pause();
      this.audio.currentTime = 0;
    }
  }

  /** When the question or language changes, the previous audio file no longer applies. */
  private resetSpeech(): void {
    this.stopSpeech();
    this.audioMissing.set(false);
  }

  protected loadQuestions(): void {
    this.loading.set(true);
    this.loadFailed.set(false);
    this.quizService
      .getRandomQuestions(QUESTIONS_PER_ROUND, this.currentLanguage())
      .subscribe({
        next: (questions) => {
          this.questions.set(questions);
          this.resetRound();
          this.loading.set(false);
        },
        error: (err) => {
          console.error('Quizfragen konnten nicht geladen werden', err);
          this.loading.set(false);
          this.loadFailed.set(true);
        },
      });
  }

  /** Language of the UI, unknown values become German. */
  private currentLanguage(): QuestionLanguage {
    const lang = (this.translate.currentLang ?? '').toLowerCase();
    return lang === 'en' || lang === 'hr' ? lang : 'de';
  }

  /**
   * Reloads the questions of the running round in the new language. Position,
   * score and the answer already given are kept, because the
   * correct letter is the same in all languages.
   *
   * If the complete round does not come back - e.g. because a language is still
   * missing in the database - the old texts stay. Better the question in
   * the wrong language than an aborted round.
   */
  private translateRound(): void {
    const numbers = this.questions().map(
      (question) => question.questionNumber
    );
    if (numbers.length === 0) {
      return;
    }
    this.quizService
      .getQuestionsByNumbers(numbers, this.currentLanguage())
      .subscribe({
        next: (questions) => {
          if (questions.length === numbers.length) {
            this.questions.set(questions);
            this.resetSpeech();
          }
        },
        error: (err) => {
          console.error('Sprachwechsel der Quizfragen fehlgeschlagen', err);
        },
      });
  }

  protected answer(letter: AnswerLetter): void {
    if (this.answered()) {
      return;
    }
    this.selected.set(letter);
    if (letter === this.current()?.correctAnswer) {
      this.rightAnswers.update((value) => value + 1);
    } else {
      this.wrongAnswers.update((value) => value + 1);
    }
  }

  protected next(): void {
    this.resetSpeech();
    if (this.index() + 1 >= this.total()) {
      this.finished.set(true);
      return;
    }
    this.index.update((value) => value + 1);
    this.selected.set(null);
  }

  protected quit(): void {
    this.resetSpeech();
    this.finished.set(true);
  }

  /** New round with new random questions. */
  protected newRound(): void {
    this.loadQuestions();
  }

  /** In the database the image paths are stored without a leading slash. */
  protected imageUrl(path: string): string {
    return path.startsWith('/') ? path : `/${path}`;
  }

  /**
   * State class of an answer button: neutral before answering, afterwards
   * the correct answer green and the wrongly chosen one red.
   */
  protected answerState(letter: AnswerLetter): string {
    if (!this.answered()) {
      return '';
    }
    if (letter === this.current()?.correctAnswer) {
      return 'is-right';
    }
    return letter === this.selected() ? 'is-wrong' : 'is-muted';
  }

  private resetRound(): void {
    this.resetSpeech();
    this.index.set(0);
    this.selected.set(null);
    this.rightAnswers.set(0);
    this.wrongAnswers.set(0);
    this.finished.set(false);
  }
}
